/**
 * Deterministically derives the docs-site migration page from the canonical
 * root MIGRATION.md. Repository-relative links are rewritten because the
 * generated page lives under docs/docs; anchors and external links stay intact.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const REPOSITORY_BLOB = "https://github.com/alpacahq/alpaca-trade-api-js/blob/master";
const LINK_REWRITES: Record<string, string> = {
    "codemods/alpaca-v3-to-v4.js": `${REPOSITORY_BLOB}/codemods/alpaca-v3-to-v4.js`,
    "codemods/README.md": `${REPOSITORY_BLOB}/codemods/README.md`,
};

export function renderDocsMigration(source: string): string {
    const body = source.replace(/\]\((codemods\/(?:alpaca-v3-to-v4\.js|README\.md))\)/g, (_match, target: string) => {
        return `](${LINK_REWRITES[target]})`;
    });

    return [
        "---",
        "sidebar_position: 2",
        "title: Migrate from 3.x",
        "---",
        "",
        "<!-- Generated by scripts/gen-docs-migration.ts from MIGRATION.md — do not edit by hand. -->",
        "",
        body.trimEnd(),
        "",
    ].join("\n");
}

function main(): void {
    const here = dirname(fileURLToPath(import.meta.url));
    const root = resolve(here, "..");
    const input = resolve(root, "MIGRATION.md");
    const output = resolve(root, "docs", "docs", "migration.md");
    writeFileSync(output, renderDocsMigration(readFileSync(input, "utf8")));
    console.log(`Wrote migration guide to ${output}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
    main();
}
