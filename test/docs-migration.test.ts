import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { describe, expect, it } from "vitest";
import { renderDocsMigration } from "../scripts/gen-docs-migration";

describe("docs migration generator", () => {
    it("adds generated frontmatter and rewrites only repository-relative links", () => {
        const source = [
            "# Migration guide",
            "",
            "[Codemod](codemods/alpaca-v3-to-v4.js)",
            "[Reference](codemods/README.md)",
            "[Section](#before-you-start)",
            "[External](https://example.com/guide)",
            "",
        ].join("\n");

        expect(renderDocsMigration(source)).toBe(
            [
                "---",
                "sidebar_position: 2",
                "title: Migrate from 3.x",
                "---",
                "",
                "<!-- Generated by scripts/gen-docs-migration.ts from MIGRATION.md — do not edit by hand. -->",
                "",
                "# Migration guide",
                "",
                "[Codemod](https://github.com/alpacahq/alpaca-trade-api-js/blob/master/codemods/alpaca-v3-to-v4.js)",
                "[Reference](https://github.com/alpacahq/alpaca-trade-api-js/blob/master/codemods/README.md)",
                "[Section](#before-you-start)",
                "[External](https://example.com/guide)",
                "",
            ].join("\n"),
        );
    });

    it("keeps the generated migration page ignored beside other generated docs", () => {
        const gitignore = readFileSync(resolve(import.meta.dirname, "..", ".gitignore"), "utf8");
        const lines = gitignore.split(/\r?\n/);
        const examplesIndex = lines.indexOf("docs/docs/examples.md");
        expect(examplesIndex).toBeGreaterThan(-1);
        expect(lines[examplesIndex + 1]).toBe("docs/docs/migration.md");
    });

    it("preserves stable 4.x install guidance", () => {
        const source = readFileSync(resolve(import.meta.dirname, "..", "MIGRATION.md"), "utf8");
        const generated = renderDocsMigration(source);

        for (const guide of [source, generated]) {
            expect(guide).toContain("npm install @alpacahq/alpaca-trade-api@^4");
            expect(guide).toContain(
                "npm install alpaca-v4@npm:@alpacahq/alpaca-trade-api@^4",
            );
            expect(guide).not.toContain("@alpha");
            expect(guide).not.toContain("prerelease");
            expect(guide).not.toContain("After stable `4.0.0` publishes");
        }
    });
});
